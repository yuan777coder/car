/* ==========================================================================
 *  main.c  —  程序入口
 *
 *  基于 STC32G144K246 的电磁感应循迹小车
 *      电感采集磁场 → RS824 运放调理 → ADC 采样 → 偏差计算
 *      → 舵机转向（PD） + 电机调速（速度环） → OLED 实时显示
 *
 *  主循环里所有实际工作都在 Car_Loop() 中完成，
 *  main() 只负责"初始化一次 + 无限循环"，便于阅读和移植。
 *
 *  编译环境：Keil uVision + C251 编译器
 *  必须包含 STC 官方头文件 STC32G.H（由 STC-ISP 下载软件生成），
 *  具体搭建步骤见 docs/keil_setup.md
 * ========================================================================== */

#include "STC32G.H"

#include "common.h"
#include "car.h"

void main(void)
{
    Car_Init();

    while (1) {
        Car_Loop();
    }
}
