#ifndef __TIMER_H
#define __TIMER_H

#include "common.h"
#include "config.h"

/* ==========================================================================
 *  timer.h  —  系统节拍（控制周期）
 *
 *  设计取舍：定时器中断里只做两件事 —— 累加毫秒计数、置"周期到"标志。
 *  真正的控制运算放在主循环里轮询标志执行。
 *  这样做的好处是中断极短，不会因为 ADC 采样 / 速度环运算把中断拉长，
 *  从而影响串口接收和 I2C 时序；5ms 的周期抖动对寻迹小车完全可以忽略。
 *
 *  定时器分配（见 board_config.h 与 docs/pinmap.md）：
 *      T3  → 本文件的系统节拍（ENCODER_ENABLE 开关都不影响它）
 *      T0/T1 → 编码器计数（仅 ENCODER_ENABLE=1）
 *      T2 → 串口波特率发生器
 * ========================================================================== */

void Timer_Init(void);

/* 主循环查询："本控制周期到了吗"；返回 1 时内部标志已清零 */
uint8 Timer_TakeFlag(void);

/* 上电以来的毫秒数（约 49 天溢出，本工程用不到那么久） */
uint32 Timer_GetMs(void);

/* 中断服务函数，只允许中断调用 */
void Timer_Isr(void);

#endif /* __TIMER_H */
