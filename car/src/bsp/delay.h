#ifndef __DELAY_H
#define __DELAY_H

#include "common.h"

/* ==========================================================================
 *  delay.h  —  软件延时
 *
 *  说明：软件延时是"大致准确"的，误差随主频设置和编译器优化等级变化。
 *  对时序有硬要求的地方（ADC、串口、PWM）一律用硬件外设，不要靠这个。
 *  这里主要用于 OLED 上电复位时序、按键消抖等毫秒级的场合。
 * ========================================================================== */

void Delay_Init(void);          /* 依据 MAIN_FREQ_KHZ 计算循环次数 */
void Delay_Us(uint16 us);
void Delay_Ms(uint16 ms);

#endif /* __DELAY_H */
